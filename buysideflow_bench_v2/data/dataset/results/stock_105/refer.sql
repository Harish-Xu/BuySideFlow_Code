WITH recent_days AS (
    SELECT TRADINGDATE FROM qt_tradingdaynew
    WHERE SECUMARKET=83 AND IFTRADINGDAY=1 AND TRADINGDATE<='2025-12-31'
    ORDER BY TRADINGDATE DESC LIMIT 30
), calendar AS (
    SELECT TRADINGDATE,ROW_NUMBER() OVER(ORDER BY TRADINGDATE) AS seq
    FROM recent_days
), stocks AS (
    SELECT s.INNERCODE,s.SECUCODE,s.SECUABBR
    FROM secumain s
    WHERE s.SECUCATEGORY=1 AND s.SECUMARKET IN (83,90)
      AND s.LISTEDSECTOR IN (1,2) AND s.LISTEDDATE<='2024-12-31'
      AND (SELECT l.CHANGETYPE FROM lc_liststatus l
           WHERE l.INNERCODE=s.INNERCODE AND l.CHANGEDATE<'2026-01-01'
             AND l.CHANGETYPE BETWEEN 1 AND 9
           ORDER BY l.CHANGEDATE DESC,l.JSID DESC,l.ID DESC LIMIT 1) IN (1,2,3,6)
      AND NOT EXISTS (
          SELECT 1 FROM cs_riskalert r WHERE r.INNERCODE=s.INNERCODE
            AND r.RISKALERTTYPE IN (1,5,12,14) AND r.IMPLEMENTDATE<'2026-01-01'
            AND COALESCE(r.IMPLANNOUCEDATE,r.INSERTTIME)<'2026-01-01'
            AND (r.REMOVEDATE IS NULL OR r.REMOVEDATE>='2026-01-01'
                 OR COALESCE(r.REMOVEINFOPUBLDATE,r.INSERTTIME)>='2026-01-01')
      )
), limits AS (
    SELECT p.INNERCODE,c.seq,
           c.seq-ROW_NUMBER() OVER(PARTITION BY p.INNERCODE ORDER BY c.seq) AS grp
    FROM stocks s JOIN qt_performancedata p ON p.INNERCODE=s.INNERCODE
    JOIN calendar c ON c.TRADINGDATE=p.TRADINGDAY WHERE p.SURGEDLIMIT=1
), lengths AS (
    SELECT INNERCODE,grp,COUNT(*) AS n FROM limits GROUP BY INNERCODE,grp
), streaks AS (
    SELECT INNERCODE,MAX(n) AS streak FROM lengths
    GROUP BY INNERCODE HAVING MAX(n)>=4
), highs AS (
    SELECT p.INNERCODE,MAX(p.BACKWARDPRICE) AS high_close
    FROM streaks s JOIN qt_performancedata p ON p.INNERCODE=s.INNERCODE
    JOIN calendar c ON c.TRADINGDATE=p.TRADINGDAY
    WHERE c.seq>10 AND p.BACKWARDPRICE>0
    GROUP BY p.INNERCODE HAVING COUNT(DISTINCT p.TRADINGDAY)=20
), final AS (
    SELECT s.SECUCODE,s.SECUABBR,l.streak,q.CLOSEPRICE,
           (1-p.BACKWARDPRICE/h.high_close)*100 AS drawdown
    FROM stocks s JOIN streaks l ON l.INNERCODE=s.INNERCODE
    JOIN highs h ON h.INNERCODE=s.INNERCODE
    JOIN qt_dailyquote q ON q.INNERCODE=s.INNERCODE AND q.TRADINGDAY='2025-12-31'
    JOIN qt_performancedata p ON p.INNERCODE=s.INNERCODE AND p.TRADINGDAY=q.TRADINGDAY
    WHERE q.CLOSEPRICE>q.PREVCLOSEPRICE AND p.BACKWARDPRICE>0
      AND p.BACKWARDPRICE>=0.95*h.high_close
)
SELECT SECUCODE AS `股票代码`,SECUABBR AS `股票简称`,
       streak AS `最近30日最大连续涨停天数`,
       ROUND(CLOSEPRICE,2) AS `观察日未复权收盘价`,
       ROUND(drawdown,2) AS `较近20日收盘高点跌幅`
FROM final ORDER BY streak DESC,drawdown ASC,SECUCODE;
