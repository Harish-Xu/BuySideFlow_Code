WITH base AS (
    SELECT s.INNERCODE,s.COMPANYCODE,s.SECUCODE,s.SECUABBR
    FROM secumain s
    WHERE s.SECUCATEGORY=1 AND s.SECUMARKET IN (83,90) AND s.LISTEDSECTOR IN (1,2,6)
      AND s.LISTEDDATE<='2024-10-28'
      AND (SELECT l.CHANGETYPE FROM lc_liststatus l
           WHERE l.INNERCODE=s.INNERCODE AND l.CHANGEDATE<'2025-10-29'
             AND l.CHANGETYPE BETWEEN 1 AND 9
           ORDER BY l.CHANGEDATE DESC,l.JSID DESC,l.ID DESC LIMIT 1) IN (1,2,3,6)
      AND NOT EXISTS (
          SELECT 1 FROM cs_riskalert r WHERE r.INNERCODE=s.INNERCODE
            AND r.RISKALERTTYPE IN (1,5,12,14) AND r.IMPLEMENTDATE<'2025-10-29'
            AND COALESCE(r.IMPLANNOUCEDATE,r.INSERTTIME)<'2025-10-29'
            AND (r.REMOVEDATE IS NULL OR r.REMOVEDATE>='2025-10-29'
                 OR COALESCE(r.REMOVEINFOPUBLDATE,r.INSERTTIME)>='2025-10-29')
      )
), industries AS (
    SELECT e.COMPANYCODE,e.FIRSTINDUSTRYCODE,
           ROW_NUMBER() OVER(PARTITION BY e.COMPANYCODE ORDER BY e.INFOPUBLDATE DESC,e.JSID DESC) rn
    FROM lc_exgindustry e JOIN base b ON b.COMPANYCODE=e.COMPANYCODE
    WHERE e.STANDARD=38 AND e.INFOPUBLDATE<'2025-10-29'
      AND (e.CANCELDATE IS NULL OR e.CANCELDATE>='2025-10-29')
), cap_versions AS (
    SELECT v.INNERCODE,v.NEGOTIABLEMV,
           ROW_NUMBER() OVER(PARTITION BY v.INNERCODE ORDER BY v.JSID DESC,v.ID DESC) rn
    FROM lc_dindicesforvaluation v JOIN base b ON b.INNERCODE=v.INNERCODE
    WHERE v.TRADINGDAY='2025-10-28'
), caps AS (
    SELECT b.*,v.NEGOTIABLEMV,PERCENT_RANK() OVER(ORDER BY v.NEGOTIABLEMV) cap_rank
    FROM base b JOIN cap_versions v ON v.INNERCODE=b.INNERCODE AND v.rn=1 WHERE v.NEGOTIABLEMV>0
), growth_main AS (
    SELECT m.COMPANYCODE,m.OPERATINGREVENUEGROWRATE AS revenue_yoy,m.NPPARENTCOMPANYCUTYOY AS profit_yoy,
           ROW_NUMBER() OVER(PARTITION BY m.COMPANYCODE ORDER BY m.INFOPUBLDATE DESC,m.JSID DESC,m.ID DESC) rn
    FROM lc_mainindexnew m JOIN base b ON b.COMPANYCODE=m.COMPANYCODE
    WHERE m.ENDDATE='2025-09-30' AND m.INFOPUBLDATE<'2025-10-29'
), growth_derivative AS (
    SELECT m.COMPANYCODE,m.OPERATINGREVENUEYOY AS revenue_yoy,m.NPPARENTCOMPANYCUTYOY AS profit_yoy,
           ROW_NUMBER() OVER(PARTITION BY m.COMPANYCODE
             ORDER BY FIELD(m.MARK,1,8,7,6,2),m.INFOPUBLDATE DESC,m.INSERTTIME DESC,m.JSID DESC) rn
    FROM fin_derivative m JOIN base b ON b.COMPANYCODE=m.COMPANYCODE
    WHERE m.ENDDATE='2025-09-30' AND m.INFOPUBLDATE<'2025-10-29' AND m.MARK IN (1,8,7,6,2)
), growth AS (
    SELECT COMPANYCODE,revenue_yoy,profit_yoy FROM growth_main WHERE rn=1
    UNION ALL
    SELECT d.COMPANYCODE,d.revenue_yoy,d.profit_yoy FROM growth_derivative d
    WHERE d.rn=1 AND NOT EXISTS(SELECT 1 FROM growth_main m WHERE m.COMPANYCODE=d.COMPANYCODE)
), cash_versions AS (
    SELECT m.COMPANYCODE,m.NETOPERATECASHFLOW,m.OPERATINGREENUE,
           ROW_NUMBER() OVER(PARTITION BY m.COMPANYCODE
             ORDER BY FIELD(m.MARK,1,8,7,6,2),m.INFOPUBLDATE DESC,m.INSERTTIME DESC,m.JSID DESC) rn
    FROM lc_maindatanew m JOIN base b ON b.COMPANYCODE=m.COMPANYCODE
    WHERE m.ENDDATE='2025-09-30' AND m.INFOPUBLDATE<'2025-10-29' AND m.MARK IN (1,8,7,6,2)
), cash AS (
    SELECT COMPANYCODE,NETOPERATECASHFLOW/OPERATINGREENUE AS ratio
    FROM cash_versions WHERE rn=1 AND OPERATINGREENUE>0 AND NETOPERATECASHFLOW IS NOT NULL
), industry_values AS (
    SELECT i.FIRSTINDUSTRYCODE,c.ratio,
           ROW_NUMBER() OVER(PARTITION BY i.FIRSTINDUSTRYCODE ORDER BY c.ratio) pos,
           COUNT(*) OVER(PARTITION BY i.FIRSTINDUSTRYCODE) n
    FROM base b JOIN industries i ON i.COMPANYCODE=b.COMPANYCODE AND i.rn=1
    JOIN cash c ON c.COMPANYCODE=b.COMPANYCODE
    WHERE i.FIRSTINDUSTRYCODE IS NOT NULL
), medians AS (
    SELECT FIRSTINDUSTRYCODE,AVG(ratio) AS median_ratio FROM industry_values
    WHERE pos IN (FLOOR((n+1)/2),FLOOR((n+2)/2)) GROUP BY FIRSTINDUSTRYCODE
), ranked AS (
    SELECT c.*,g.revenue_yoy,g.profit_yoy,
           PERCENT_RANK() OVER(ORDER BY g.revenue_yoy DESC) AS growth_rank
    FROM caps c JOIN growth g ON g.COMPANYCODE=c.COMPANYCODE
    WHERE c.cap_rank<=0.4 AND g.revenue_yoy IS NOT NULL
)
SELECT r.SECUCODE AS `股票代码`,r.SECUABBR AS `股票简称`,
       ROUND(r.revenue_yoy,2) AS `营业收入同比增速`,
       ROUND(r.profit_yoy,2) AS `扣非归母净利润同比增速`,
       ROUND(c.ratio*100,2) AS `经营现金流与营业收入之比`,
       ROUND(m.median_ratio*100,2) AS `行业中位数`,
       ROUND(r.NEGOTIABLEMV/100000000,2) AS `流通市值`
FROM ranked r JOIN cash c ON c.COMPANYCODE=r.COMPANYCODE
JOIN industries i ON i.COMPANYCODE=r.COMPANYCODE AND i.rn=1
JOIN medians m ON m.FIRSTINDUSTRYCODE=i.FIRSTINDUSTRYCODE
WHERE r.growth_rank<=0.1 AND r.revenue_yoy-r.profit_yoy>30 AND c.ratio<m.median_ratio
ORDER BY r.revenue_yoy-r.profit_yoy DESC,r.SECUCODE;
