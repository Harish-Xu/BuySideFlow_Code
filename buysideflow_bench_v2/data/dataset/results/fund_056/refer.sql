WITH params AS (
    SELECT DATE('2026-02-13') AS observation_date
)
SELECT
    sm.SECUCODE AS fund_code,
    COALESCE(sm.SECUABBR, sm.CHINAMEABBR) AS fund_name,
    f.EXAPPLYINGCODE AS ex_applying_code,
    f.EXAPPLYINGABBR AS ex_applying_abbr
FROM mf_fundarchives f
JOIN secumain sm
  ON sm.INNERCODE = f.INNERCODE
JOIN params p
WHERE f.FUNDTYPECODE = 1109
  AND f.TYPE = 2
  AND sm.SECUCATEGORY = 8
  AND f.ESTABLISHMENTDATE <= p.observation_date
  AND (f.EXPIREDATE IS NULL OR f.EXPIREDATE > p.observation_date)
  AND (sm.LISTEDDATE IS NULL OR sm.LISTEDDATE <= p.observation_date)
  AND COALESCE(NULLIF(TRIM(sm.SECUCODE), ''), NULL) IS NOT NULL
  AND COALESCE(NULLIF(TRIM(f.EXAPPLYINGCODE), ''), NULL) IS NOT NULL
  AND COALESCE(NULLIF(TRIM(f.EXAPPLYINGABBR), ''), NULL) IS NOT NULL
ORDER BY sm.SECUCODE, f.EXAPPLYINGCODE;
