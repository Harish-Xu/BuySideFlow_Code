WITH universe AS (
    SELECT DISTINCT ix.SECUCODE AS index_code,
           CASE ix.SECUCODE WHEN '000300' THEN '沪深300' ELSE '中证500' END AS index_name,
           s.COMPANYCODE,s.LISTEDSECTOR
    FROM secumain ix JOIN lc_indexcomponent ic ON ic.INDEXINNERCODE=ix.INNERCODE
    JOIN secumain s ON s.INNERCODE=ic.SECUINNERCODE
    WHERE ix.SECUCATEGORY=4 AND ix.SECUCODE IN ('000300','000905')
      AND s.SECUCATEGORY=1 AND s.SECUMARKET IN (83,90)
      AND ic.INDATE<='2025-04-25' AND (ic.OUTDATE IS NULL OR ic.OUTDATE>'2025-04-25')
), companies AS (SELECT DISTINCT COMPANYCODE,LISTEDSECTOR FROM universe),
industry AS (
    SELECT e.COMPANYCODE,e.FIRSTINDUSTRYNAME,e.INFOPUBLDATE,e.JSID
    FROM lc_exgindustry e JOIN companies c ON c.COMPANYCODE=e.COMPANYCODE
    WHERE e.STANDARD=38 AND e.INFOPUBLDATE<'2025-04-26'
      AND (e.CANCELDATE IS NULL OR e.CANCELDATE>'2025-04-25')
    UNION ALL
    SELECT e.COMPANYCODE,e.FIRSTINDUSTRYNAME,e.INFOPUBLDATE,e.JSID
    FROM lc_stibexgindustry e JOIN companies c ON c.COMPANYCODE=e.COMPANYCODE
    WHERE e.STANDARD=38 AND e.INFOPUBLDATE<'2025-04-26'
      AND (e.CANCELDATE IS NULL OR e.CANCELDATE>'2025-04-25')
), industry_ranked AS (
    SELECT *,ROW_NUMBER() OVER(PARTITION BY COMPANYCODE ORDER BY INFOPUBLDATE DESC,JSID DESC) rn FROM industry
), sample AS (
    SELECT c.* FROM companies c JOIN industry_ranked e ON e.COMPANYCODE=c.COMPANYCODE AND e.rn=1
    WHERE e.FIRSTINDUSTRYNAME NOT IN ('银行','非银金融')
), primary_metrics AS (
    SELECT m.COMPANYCODE,m.ENDDATE,m.INFOPUBLDATE,m.INSERTTIME,m.JSID,
           m.ROA,m.LONGDEBTTOASSET,m.CURRENTRATIO,m.GROSSINCOMERATIO,m.TOTALASSETTRATE,
           NULL AS CFO,NULL AS NP
    FROM lc_mainindexnew m JOIN sample s ON s.COMPANYCODE=m.COMPANYCODE AND s.LISTEDSECTOR<>7
    WHERE m.ENDDATE IN ('2022-12-31','2023-12-31','2024-12-31') AND m.INFOPUBLDATE<'2025-04-26'
    UNION ALL
    SELECT m.COMPANYCODE,m.ENDDATE,m.INFOPUBLDATE,m.INSERTTIME,m.JSID,
           m.ROA,m.LONGDEBTTOASSET,m.CURRENTRATIO,m.GROSSINCOMERATIO,m.TOTALASSETTRATE,
           m.NETOPERATECASHFLOW,m.NPPARENTCOMPANYOWNERS
    FROM lc_stibmainindex m JOIN sample s ON s.COMPANYCODE=m.COMPANYCODE AND s.LISTEDSECTOR=7
    WHERE m.ENDDATE IN ('2022-12-31','2023-12-31','2024-12-31') AND m.INFOPUBLDATE<'2025-04-26' AND m.IFMERGED=1
), metrics AS (
    SELECT *,ROW_NUMBER() OVER(PARTITION BY COMPANYCODE,ENDDATE
        ORDER BY INFOPUBLDATE DESC,INSERTTIME DESC,JSID DESC) rn FROM primary_metrics
), derivatives AS (
    SELECT m.*,ROW_NUMBER() OVER(PARTITION BY m.COMPANYCODE,m.ENDDATE
        ORDER BY FIELD(m.MARK,1,8,7,6,2),m.INFOPUBLDATE DESC,m.INSERTTIME DESC,m.JSID DESC) rn
    FROM fin_derivative m JOIN sample s ON s.COMPANYCODE=m.COMPANYCODE
    WHERE m.ENDDATE IN ('2022-12-31','2023-12-31','2024-12-31')
      AND m.INFOPUBLDATE<'2025-04-26' AND m.MARK IN (1,8,7,6,2)
), raw_annual AS (
    SELECT m.*,ROW_NUMBER() OVER(PARTITION BY m.COMPANYCODE,m.ENDDATE
        ORDER BY FIELD(m.MARK,1,8,7,6,2),m.INFOPUBLDATE DESC,m.INSERTTIME DESC,m.JSID DESC) rn
    FROM lc_maindatanew m JOIN sample s ON s.COMPANYCODE=m.COMPANYCODE
    WHERE m.ENDDATE IN ('2022-12-31','2023-12-31','2024-12-31')
      AND m.INFOPUBLDATE<'2025-04-26' AND m.MARK IN (1,8,7,6,2)
      AND COALESCE(m.ACCOUNTINGSTANDARDS,1)=1
), years AS (
    SELECT DATE('2022-12-31') AS dt UNION ALL SELECT DATE('2023-12-31') UNION ALL SELECT DATE('2024-12-31')
), star_shares AS (
    SELECT h.COMPANYCODE,y.dt,h.TOTALSHARES,
           ROW_NUMBER() OVER(PARTITION BY h.COMPANYCODE,y.dt ORDER BY h.ENDDATE DESC,h.INFOPUBLDATE DESC,h.JSID DESC) rn
    FROM sample s JOIN lc_sharestru h ON h.COMPANYCODE=s.COMPANYCODE
    JOIN years y ON h.ENDDATE<=y.dt
    WHERE s.LISTEDSECTOR=7 AND COALESCE(h.INFOPUBLDATE,h.INSERTTIME)<'2025-04-26'
), annual AS (
    SELECT s.COMPANYCODE,y.dt,
           COALESCE(m.ROA,f.ROA) AS roa,
           COALESCE(m.LONGDEBTTOASSET,f.LONGDEBTTOASSET / IF(s.LISTEDSECTOR=7,1,100)) AS leverage,
           COALESCE(m.CURRENTRATIO,f.CURRENTRATIO) AS liquidity,
           COALESCE(m.GROSSINCOMERATIO,f.GROSSINCOMERATIO) AS margin,
           COALESCE(m.TOTALASSETTRATE,f.TOTALASSETTRATE) AS turnover,
           CASE WHEN s.LISTEDSECTOR=7 THEN m.CFO ELSE r.NETOPERATECASHFLOW END AS cfo,
           CASE WHEN s.LISTEDSECTOR=7 THEN m.NP ELSE r.NPFROMPARENTCOMPANYOWNERS END AS np,
           CASE WHEN s.LISTEDSECTOR=7 THEN COALESCE(h.TOTALSHARES,f.TOTALSHARES,r.TOTALSHARES) ELSE r.TOTALSHARES END AS shares
    FROM sample s CROSS JOIN years y
    LEFT JOIN metrics m ON m.COMPANYCODE=s.COMPANYCODE AND m.ENDDATE=y.dt AND m.rn=1
    LEFT JOIN derivatives f ON f.COMPANYCODE=s.COMPANYCODE AND f.ENDDATE=y.dt AND f.rn=1
    LEFT JOIN raw_annual r ON r.COMPANYCODE=s.COMPANYCODE AND r.ENDDATE=y.dt AND r.rn=1
    LEFT JOIN star_shares h ON h.COMPANYCODE=s.COMPANYCODE AND h.dt=y.dt AND h.rn=1
), complete AS (
    SELECT COMPANYCODE FROM annual GROUP BY COMPANYCODE
    HAVING COUNT(roa)=3 AND COUNT(leverage)=3 AND COUNT(liquidity)=3 AND COUNT(margin)=3
       AND COUNT(turnover)=3 AND COUNT(shares)=3
       AND SUM(dt>'2022-12-31' AND cfo IS NOT NULL AND np IS NOT NULL)=2
), scored AS (
    SELECT a.COMPANYCODE,a.dt,
           (a.roa>0)+(a.cfo>0)+(a.roa>b.roa)+(a.cfo>a.np)
           +(a.leverage<b.leverage)+(a.liquidity>b.liquidity)+(a.shares<=b.shares)
           +(a.margin>b.margin)+(a.turnover>b.turnover) AS score
    FROM annual a JOIN annual b ON b.COMPANYCODE=a.COMPANYCODE AND b.dt=DATE_SUB(a.dt,INTERVAL 1 YEAR)
    JOIN complete c ON c.COMPANYCODE=a.COMPANYCODE
)
SELECT u.index_name AS `指数`, COUNT(DISTINCT s.COMPANYCODE) AS `可比样本数`,
       ROUND(AVG(CASE WHEN s.dt='2023-12-31' THEN s.score END),2) AS `2023年平均F-Score`,
       ROUND(AVG(CASE WHEN s.dt='2024-12-31' THEN s.score END),2) AS `2024年平均F-Score`
FROM universe u JOIN scored s ON s.COMPANYCODE=u.COMPANYCODE
GROUP BY u.index_code,u.index_name ORDER BY u.index_code;
