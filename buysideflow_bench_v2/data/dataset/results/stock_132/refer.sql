WITH reports AS (
    SELECT l.*, ROW_NUMBER() OVER (
        ORDER BY l.ENDDATE DESC, l.INFOPUBLDATE DESC, l.INSERTTIME DESC, l.JSID DESC
    ) AS rn
    FROM lc_mainindexnew l
    JOIN secumain s ON s.COMPANYCODE = l.COMPANYCODE
    WHERE s.SECUCODE = '601398' AND s.SECUMARKET = 83 AND s.SECUCATEGORY = 1
      AND l.INFOPUBLDATE < '2025-03-21'
      AND l.ENDDATE < '2025-03-21' AND DATE_FORMAT(l.ENDDATE, '%m-%d') = '12-31'
)
SELECT DATE_FORMAT(ENDDATE, '%Y-%m-%d') AS `报告期`,
       ROUND(NETASSETPS, 2) AS `年报期末每股净资产`,
       ROUND(ROEAVG, 2) AS `平均净资产收益率`,
       ROUND(RETAINEDEARNINGRATIO, 2) AS `留存盈余比率`,
       ROUND(NETASSETPS * POW(1 + ROEAVG * RETAINEDEARNINGRATIO / 10000,
                             2027 - YEAR(ENDDATE)), 2) AS `2027年末每股净资产测算值`
FROM reports
WHERE rn = 1 AND NETASSETPS IS NOT NULL AND ROEAVG IS NOT NULL
  AND RETAINEDEARNINGRATIO IS NOT NULL;
