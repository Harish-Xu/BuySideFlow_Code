SELECT
    bc.MAINCODE,
    bc.INNERCODE,
    bc.SECUCODE AS bond_code,
    bc.SECUABBR AS bond_abbr,
    bc.SECUMARKET,
    v.ENDDATE AS valuation_date,
    v.TRUEREMAINMATURITY AS remaining_years,
    v.VPADURATION AS modified_duration,
    v.VPYIELD AS valuation_yield_pct
FROM (
    SELECT
        v.*,
        ROW_NUMBER() OVER (
            PARTITION BY v.INNERCODE
            ORDER BY v.UPDATETIME DESC, v.INSERTTIME DESC, v.ID DESC
        ) AS rn
    FROM bond_cbvaluationall v FORCE INDEX (IX_BOND_CBVALUATIONALL_N1)
    WHERE v.ENDDATE >= '2025-03-21'
      AND v.ENDDATE < DATE_ADD('2025-03-21', INTERVAL 1 DAY)
      AND v.CREDIBILITYCODE = 1
      AND v.YIELDCODE = 2
      AND v.VPYIELD IS NOT NULL
      AND v.VPADURATION IS NOT NULL
      AND v.TRUEREMAINMATURITY >= 7
      AND v.TRUEREMAINMATURITY < 15
      AND v.VPADURATION > 7
      AND (v.INSERTTIME IS NULL OR v.INSERTTIME < DATE_ADD('2025-03-21', INTERVAL 1 DAY))
      AND (v.UPDATETIME IS NULL OR v.UPDATETIME < DATE_ADD('2025-03-21', INTERVAL 1 DAY))
) v
JOIN bond_code bc
  ON bc.INNERCODE = v.INNERCODE
LEFT JOIN bond_basicinfo bi
  ON bi.MAINCODE = bc.MAINCODE
WHERE v.rn = 1
  AND bc.MAINCODE IS NOT NULL
  AND bc.INNERCODE IS NOT NULL
  AND (
        bc.BONDNATURE = 4
        OR bc.BONDTYPELEVEL1 = 1000
        OR bc.BONDTYPELEVEL2 = 1201
      )
  AND (bi.ISSUEDATE IS NULL OR bi.ISSUEDATE <= '2025-03-21')
  AND (bi.VALUEDATE IS NULL OR bi.VALUEDATE <= '2025-03-21')
  AND (bc.LISTEDDATE IS NULL OR bc.LISTEDDATE <= '2025-03-21')
  AND (bc.INTERESTENDDATE IS NULL OR bc.INTERESTENDDATE >= '2025-03-21')
  AND (bc.DELISTDATE IS NULL OR bc.DELISTDATE >= '2025-03-21');
