SELECT
    DATE(v.ENDDATE) AS valuation_date
FROM bond_cbvaluationall v FORCE INDEX (IX_BOND_CBVALUATIONALL_N1)
JOIN bond_code b ON b.INNERCODE = v.INNERCODE
WHERE b.SECUMARKET = 89
  AND v.CREDIBILITYCODE = 1
  AND v.YIELDCODE = 2
  AND v.VPYIELD IS NOT NULL
  AND v.ENDDATE < DATE('2025-06-01')
  AND v.INSERTTIME < TIMESTAMP('2025-06-01')
ORDER BY v.ENDDATE DESC
LIMIT 1;
