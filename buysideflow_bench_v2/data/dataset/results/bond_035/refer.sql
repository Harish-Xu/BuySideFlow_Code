SELECT
    bc.MAINCODE AS maincode,
    GROUP_CONCAT(CAST(bc.INNERCODE AS CHAR) ORDER BY bc.INNERCODE SEPARATOR ',') AS innercodes
FROM bond_code bc
WHERE bc.BONDTYPELEVEL1 = 1800
  AND bc.MAINCODE IS NOT NULL
  AND bc.INNERCODE IS NOT NULL
  AND bc.INTERESTENDDATE IS NOT NULL
  AND bc.INTERESTENDDATE >= DATE_ADD(DATE('2024-12-31'), INTERVAL 1 YEAR)
  AND bc.INTERESTENDDATE <= DATE_ADD(DATE('2024-12-31'), INTERVAL 5 YEAR)
  AND (bc.LISTEDDATE IS NULL OR bc.LISTEDDATE < DATE('2025-01-01'))
  AND (bc.DELISTDATE IS NULL OR bc.DELISTDATE >= DATE('2024-12-31'))
GROUP BY bc.MAINCODE;
